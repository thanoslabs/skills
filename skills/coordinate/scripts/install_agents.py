#!/usr/bin/env python3
"""Install coordinate's worker roles as native agent definitions.

The source of truth is assets/roles/*.md: tool-neutral frontmatter plus
instructions. This renders them into each agent tool's own format, so the
tool enforces the model and whatever capability limits it supports.
Installing is optional; without it, coordinate passes the role files to
whatever subagent mechanism the session has.

Requires: python3 (standard library only).

Usage:
  install_agents.py --target claude|codex|all [--scope user|project]
                    [--codex-model MODEL] [--dry-run] [--force] [--remove]

  --scope user      ~/.claude/agents, ~/.codex/agents (default)
  --scope project   <git toplevel>/.claude/agents, <git toplevel>/.codex/agents
  --codex-model     model for Codex agents; otherwise they inherit the session's
  --force           overwrite agent files this script did not generate
  --remove          delete the agent files this script generated
"""

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

SKILL_DIR = Path(__file__).resolve().parents[1]
ROLES_DIR = SKILL_DIR / "assets" / "roles"
MARKER = "Generated by coordinate/scripts/install_agents.py"

# Tool-neutral capabilities -> Claude Code tool names.
CLAUDE_TOOLS = {
    "read": ["Read", "Grep", "Glob"],
    "shell": ["Bash"],
    "write": ["Write"],
    "edit": ["Edit"],
}
KNOWN_CAPABILITIES = set(CLAUDE_TOOLS)


def die(msg):
    print(f"install_agents.py: {msg}", file=sys.stderr)
    sys.exit(1)


def parse_role(path):
    """Split a role file into (frontmatter dict, body). Values are strings,
    or lists for `[a, b]` values; that's all the role files use."""
    text = path.read_text()
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        die(f"{path}: missing frontmatter")
    meta = {}
    for line in m.group(1).splitlines():
        key, sep, value = line.partition(":")
        if not sep:
            die(f"{path}: bad frontmatter line {line!r}")
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            value = [v.strip() for v in value[1:-1].split(",") if v.strip()]
        meta[key.strip()] = value
    for key in ("name", "description", "capabilities"):
        if key not in meta:
            die(f"{path}: frontmatter needs `{key}`")
    unknown = set(meta["capabilities"]) - KNOWN_CAPABILITIES
    if unknown:
        die(f"{path}: unknown capabilities {sorted(unknown)}")
    body = m.group(2).strip().replace("<skill dir>", str(SKILL_DIR))
    return meta, body


def render_claude(meta, body, _args):
    tools = [t for cap in ("read", "shell", "write", "edit")
             if cap in meta["capabilities"] for t in CLAUDE_TOOLS[cap]]
    lines = ["---", f"name: {meta['name']}", f"description: {meta['description']}"]
    if meta.get("claude_model"):
        lines.append(f"model: {meta['claude_model']}")
    lines += [f"tools: {', '.join(tools)}", "---", "",
              f"<!-- {MARKER} from assets/roles. Edit the source and re-run. -->", "", body, ""]
    return "\n".join(lines)


def toml_str(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_codex(meta, body, args):
    if "'''" in body:
        die(f"{meta['name']}: instructions contain ''' and can't be a TOML literal string")
    lines = [f"# {MARKER} from assets/roles. Edit the source and re-run.",
             f"name = {toml_str(meta['name'])}",
             f"description = {toml_str(meta['description'])}"]
    model = args.codex_model or meta.get("codex_model")
    if model:
        lines.append(f"model = {toml_str(model)}")
    # Codex has no per-tool allowlist and no read-only sandbox per agent;
    # turning off the shell is the only capability limit it offers.
    lines.append(f"developer_instructions = '''\n{body}\n'''")
    if "shell" not in meta["capabilities"]:
        lines += ["", "[features]", "shell_tool = false"]
    return "\n".join(lines) + "\n"


def project_root():
    try:
        out = subprocess.run(["git", "rev-parse", "--show-toplevel"],
                             capture_output=True, text=True, check=True)
    except (OSError, subprocess.CalledProcessError):
        die("--scope project must run inside a git repository")
    return Path(out.stdout.strip())


def destination(target, scope):
    if scope == "project":
        return project_root() / f".{target}" / "agents"
    if target == "claude":
        return Path(os.environ.get("CLAUDE_CONFIG_DIR", Path.home() / ".claude")) / "agents"
    return Path(os.environ.get("CODEX_HOME", Path.home() / ".codex")) / "agents"


TARGETS = {"claude": (render_claude, ".md"), "codex": (render_codex, ".toml")}


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--target", required=True, choices=[*TARGETS, "all"])
    p.add_argument("--scope", default="user", choices=["user", "project"])
    p.add_argument("--codex-model")
    p.add_argument("--dry-run", action="store_true")
    p.add_argument("--force", action="store_true")
    p.add_argument("--remove", action="store_true")
    args = p.parse_args()

    roles = sorted(ROLES_DIR.glob("*.md"))
    if not roles:
        die(f"no role files in {ROLES_DIR}")
    targets = list(TARGETS) if args.target == "all" else [args.target]

    # Plan every write first, so a refusal never leaves a half-done install.
    plan = []
    for target in targets:
        render, ext = TARGETS[target]
        dest_dir = destination(target, args.scope)
        for role in roles:
            meta, body = parse_role(role)
            dest = dest_dir / f"{meta['name']}{ext}"
            ours = dest.exists() and MARKER in dest.read_text()
            if args.remove:
                if ours:
                    plan.append(("remove", dest, None))
                continue
            if dest.exists() and not ours and not args.force:
                die(f"{dest} exists and wasn't generated by this script (use --force)")
            plan.append(("update" if dest.exists() else "create", dest, render(meta, body, args)))

    for action, dest, content in plan:
        print(f"{action}  {dest}")
        if args.dry_run:
            continue
        if action == "remove":
            dest.unlink()
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(content)

if __name__ == "__main__":
    main()
